def extra_files(spec: DockerDbSpec) -> list[tuple[str, str]]:
    """Non-compose files an instance needs on disk, as ``(relpath, content)``.

    PostgreSQL HA mounts an init script into the primary to bootstrap streaming replication.
    SQL Server has no init hook and its AG spans containers, so it ships a setup script the
    provisioner runs once the nodes are healthy. Other engines/modes need none.
    """
    if spec.engine == "postgres" and spec.is_ha:
        return [("initdb/10-replication.sh", POSTGRES_HA_INITDB)]
    if spec.engine == "mssql" and spec.is_ha:
        return [("setup/setup_ag.sh", render(MSSQL_AG_SETUP, build_context(spec)))]
    if spec.engine == "oracle" and spec.is_ha:
        return [("setup/setup_dataguard.sh", render(ORACLE_DG_SETUP, build_context(spec))),
                ("ship/ship_loop.sh", ORACLE_DG_SHIP_LOOP)]
    return []


def post_start_commands(spec: DockerDbSpec) -> list[list[str]]:
    """Commands the provisioner runs (in the instance dir) once the nodes are healthy.

    SQL Server (availability group) and Oracle (Data Guard) need one: their HA cannot be
    created by compose or an image init hook, because the steps span the containers and
    must run in order."""
    if spec.engine == "mssql" and spec.is_ha:
        return [["bash", "setup/setup_ag.sh"]]
    if spec.engine == "oracle" and spec.is_ha:
        return [["bash", "setup/setup_dataguard.sh"]]
    return []


def template_path(engine: str, mode: str) -> Path:
    """Path to the compose template for (engine, mode)."""
    folder = "ha-lab" if mode == "ha-lab" else "single"
    path = TEMPLATES_DIR / engine / folder / "docker-compose.yml.j2"
    if not path.exists():
        raise FileNotFoundError(f"No docker-compose template for engine={engine} mode={mode}: {path}")
    return path


def load_template(engine: str, mode: str) -> str:
    return template_path(engine, mode).read_text(encoding="utf-8")


def build_context(spec: DockerDbSpec) -> dict[str, Any]:
    """Build the render context for a spec.

    ``DB_PASSWORD`` is intentionally NOT part of this context: the password only
    ever lands in the ``.env`` file, never in the committed compose YAML.
    """
    meta = spec.meta
    image = f"{meta.image_repo}:{spec.version}"
    ctx: dict[str, Any] = {
        "name": spec.name,
        "engine": spec.engine,
        "version": spec.version,
        "image": image,
        "host_port": spec.host_port,
        "container_port": meta.container_port,
        "username": meta.username,
        "database": meta.database,
        # A list rather than a string because the renderer has {% for %} but no {% if %}: an empty
        # list is how a template says "no bind mount" without a conditional.
        "bind_mounts": [spec.resolved_backup_mount] if spec.resolved_backup_mount else [],
        # Always set, never blank: every template pins its network so Docker's default pool cannot
        # hand this lab a range the estate already routes to a real database. See
        # models.lab_network_subnet for the two outages that made this non-optional.
        "network_subnet": spec.resolved_network_subnet,
    }
    if spec.is_ha:
        nodes = _ha_nodes(spec)
        ctx["nodes"] = nodes
        # Split lists let templates render master/slave blocks without needing
        # an {% if %} construct (the renderer only supports {{ }} and {% for %}).
        ctx["primary_nodes"] = [n for n in nodes if n["is_primary"]]
        ctx["standby_nodes"] = [n for n in nodes if not n["is_primary"]]
        # SQL Server's availability group is built by a script, not by compose, so it needs the
        # node names as shell arrays plus the names of the group and its seeded database.
        names = [n["service"] for n in nodes]
        ctx["ag_name"] = f"ag_{spec.name}"
        ctx["ag_database"] = f"{spec.name}_db"
        ctx["primary_node"] = names[0]
        ctx["node_list"] = " ".join(f'"{name}"' for name in names)
        ctx["secondary_list"] = " ".join(f'"{name}"' for name in names[1:])
        # Oracle Data Guard is strictly 1/1, so its script wants the single standby by name.
        ctx["standby_node"] = names[1] if len(names) > 1 else ""
    return ctx


def _slot_name(service_name: str) -> str:
    """Fold a service name into a legal physical replication slot name.

    PostgreSQL restricts slot names to lowercase letters, digits and underscores, so the
    dashes in ``<name>-standby-1`` have to go or ``pg_basebackup -S`` is rejected.
    """
    return "".join(
        char if (char.isalnum() and not char.isupper()) else ("_" if not char.isalnum() else char.lower())
        for char in service_name
    )


def _ha_nodes(spec: DockerDbSpec) -> list[dict[str, Any]]:
    """Per-service context rows for an HA lab compose.

    The first node is the primary (published on ``--host-port``); each standby
    is published on an incrementing port so every member is reachable on the
    single worker. ``partner_nodes`` is the repmgr/replication peer list.
    """
    names = spec.node_names()
    rows: list[dict[str, Any]] = []
    for index, node_name in enumerate(names):
        is_primary = index == 0
        rows.append(
            {
                "service": node_name,
                "role": "primary" if is_primary else "standby",
                "is_primary": is_primary,
                "host_port": spec.host_port + index,
                "node_index": index + 1,
                "partner_nodes": ",".join(names),
                "primary_host": names[0],
                # Physical replication slot this node streams through. A slot name may only
                # hold lowercase letters, digits and underscores, so the service name's dashes
                # are folded — pg_ha_01-standby-1 -> pg_ha_01_standby_1.
                "slot_name": _slot_name(node_name),
            }
        )
    return rows
