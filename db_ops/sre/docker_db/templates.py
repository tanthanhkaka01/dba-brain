"""Locate and render the docker-compose templates for lab database instances.

The project does not depend on Jinja2, so this module ships a tiny, well-tested
renderer that supports exactly the two constructs the templates need:

* ``{{ dotted.path }}``            - scalar substitution against the context
* ``{% for x in items %}..{% endfor %}`` - single-level iteration over a list

That keeps the ``.j2`` files under ``tools/db_ops/templates/docker`` the single
source of truth for the generated compose files (no compose YAML is hand-built
in Python) while avoiding a new runtime dependency.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from db_ops.sre.docker_db.models import DockerDbSpec

# The .j2 templates ship *inside* the package (db_ops/sre/docker_db/templates/docker)
# so they travel with `COPY db_ops ./db_ops` into the worker image — a sibling
# tools/db_ops/templates dir would NOT be in the image or the deploy bundle.
TEMPLATES_DIR = Path(__file__).resolve().parent / "templates" / "docker"

_VAR_RE = re.compile(r"{{\s*([A-Za-z0-9_.]+)\s*}}")
_FOR_RE = re.compile(
    r"{%\s*for\s+(\w+)\s+in\s+([A-Za-z0-9_.]+)\s*%}(.*?){%\s*endfor\s*%}",
    re.DOTALL,
)


def _resolve(path: str, ctx: dict[str, Any]) -> Any:
    cur: Any = ctx
    for part in path.split("."):
        if isinstance(cur, dict):
            cur = cur.get(part)
        else:
            cur = getattr(cur, part, None)
        if cur is None:
            return None
    return cur


def _render_scalars(text: str, ctx: dict[str, Any]) -> str:
    def _sub(match: re.Match[str]) -> str:
        value = _resolve(match.group(1), ctx)
        return "" if value is None else str(value)

    return _VAR_RE.sub(_sub, text)


def render(template_text: str, ctx: dict[str, Any]) -> str:
    """Render ``template_text`` with ``ctx``. Loops are expanded first (each
    iteration sees the loop variable plus a ``loop`` helper), then scalars."""

    def _expand_for(match: re.Match[str]) -> str:
        var, list_path, body = match.group(1), match.group(2), match.group(3)
        items = _resolve(list_path, ctx) or []
        chunks: list[str] = []
        total = len(items)
        for index, item in enumerate(items):
            loop = {
                "index": index + 1,
                "index0": index,
                "first": index == 0,
                "last": index == total - 1,
            }
            chunks.append(_render_scalars(body, {**ctx, var: item, "loop": loop}))
        return "".join(chunks)

    expanded = _FOR_RE.sub(_expand_for, template_text)
    return _render_scalars(expanded, ctx)


